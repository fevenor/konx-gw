// des 单块（与官方 SDK 参考实现一致）：mode 0=加密 1=解密。in/out/key 各取
// 8 字节。
//
// 与教科书 DES 的唯一偏差在密钥调度：
//   - 加密：轮 1 不轮转；轮 2..16 每轮先左转 shift[17-round] 格
//     （等效每轮比教科书少转 1 格 —— "PC-1 位序整体 +1 偏移"的来源）
//   - 解密：每轮 1..16 先右转 shift[round-1] 格
func des(in, out, key []byte, mode int) {
	var wk [176]byte // [0..63]=key 位，[64..127]=数据位，[128..175]=PC2/S 输出暂存

	// key 8B → 64 位（MSB first）
	for i := 0; i < 8; i++ {
		b := key[i]
		wk[i*8] = b >> 7
		wk[i*8+1] = b >> 6 & 1
		wk[i*8+2] = b >> 5 & 1
		wk[i*8+3] = b >> 4 & 1
		wk[i*8+4] = b >> 3 & 1
		wk[i*8+5] = b >> 2 & 1
		wk[i*8+6] = b >> 1 & 1
		wk[i*8+7] = b & 1
	}
	// 数据 8B → 64 位 @ wk[0x40..0x7f]
	for i := 0; i < 8; i++ {
		b := in[i]
		wk[0x40+i*8] = b >> 7
		wk[0x40+i*8+1] = b >> 6 & 1
		wk[0x40+i*8+2] = b >> 5 & 1
		wk[0x40+i*8+3] = b >> 4 & 1
		wk[0x40+i*8+4] = b >> 3 & 1
		wk[0x40+i*8+5] = b >> 2 & 1
		wk[0x40+i*8+6] = b >> 1 & 1
		wk[0x40+i*8+7] = b & 1
	}

	// IP → L/R（lr[0..31]=L、lr[32..63]=R）
	var lr [64]byte
	for i, s := range ipL {
		lr[i] = wk[s]
	}
	for i, s := range ipR {
		lr[32+i] = wk[s]
	}
	// PC-1 → cd[56]（C=cd[0..27]，D=cd[28..55]）
	var cd [56]byte
	for i, s := range pc1C {
		cd[i] = wk[s]
	}
	for i, s := range pc1D {
		cd[28+i] = wk[s]
	}

	for round := 1; round <= 16; round++ {
		// 保存当前 R（Feistel 新 L 的来源）
		copy(wk[0x40:0x60], lr[32:64])

		// 密钥轮转（变体所在，见函数注释）
		if mode == 0 {
			if round > 1 {
				n := int(desShift[17-round])
				rotLeft28(cd[:28], n)
				rotLeft28(cd[28:], n)
			}
		} else {
			n := int(desShift[round-1])
			rotRight28(cd[:28], n)
			rotRight28(cd[28:], n)
		}

		// E 扩展（← wk[0x5f,0x40,…]）
		var e [48]byte
		for i, s := range eSel {
			e[i] = wk[s]
		}
		// PC-2 → wk[0x80..0xaf]
		for i, s := range pc2 {
			wk[0x80+i] = cd[s]
		}
		// 轮密钥异或
		for i := 0; i < 48; i++ {
			e[i] ^= wk[0x80+i]
		}
		// S 盒 ×8（行 = b0*2+b5，列 = b1..b4，输出经 desBinary 展开）
		for s := 0; s < 8; s++ {
			g := e[6*s : 6*s+6]
			idx := (int(g[0])*2+int(g[5]))*16 +
				int(g[1])*8 + int(g[2])*4 + int(g[3])*2 + int(g[4])
			v := int(desS[s][idx])
			for j := 0; j < 4; j++ {
				wk[0x80+s*4+j] = desBinary[v*4+j]
			}
		}
		// R' = L ^ P(S)；L' = 旧 R
		for i := 0; i < 32; i++ {
			lr[32+i] = lr[i] ^ wk[0x80+pSel[i]]
			lr[i] = wk[0x40+i]
		}
	}

	// 末轮交换
	for i := 0; i < 32; i++ {
		lr[i], lr[32+i] = lr[32+i], lr[i]
	}
	// FP
	for i, s := range fpSel {
		wk[0x40+i] = lr[s]
	}
	// 位 → 字节（MSB first）
	for i := 0; i < 8; i++ {
		var b byte
		for j := 0; j < 8; j++ {
			b = b<<1 | wk[0x40+i*8+j]&1
		}
		out[i] = b
	}
}

// rotLeft28/rotRight28：C/D 半 28 位循环轮转。
func rotLeft28(h []byte, n int) {
	for t := 0; t < n; t++ {
		top := h[27]
		for j := 27; j > 0; j-- {
			h[j] = h[j-1]
		}
		h[0] = top
	}
}

func rotRight28(h []byte, n int) {
	for t := 0; t < n; t++ {
		bottom := h[0]
		for j := 0; j < 27; j++ {
			h[j] = h[j+1]
		}
		h[27] = bottom
	}
}
